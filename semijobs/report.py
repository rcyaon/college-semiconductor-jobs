"""Write results as GitHub-friendly Markdown plus JSON/CSV data files."""
import csv
import json
from datetime import date, timedelta
from pathlib import Path

NEW_DAYS = 7  # jobs first seen within this many days get a 🆕 badge


def _cell(text):
    return (text or "").replace("|", "/").replace("\n", " ").strip()


def _sort_key(job):
    posted = job["posted"] if job["posted"][:2] == "20" else "0000"  # "30+ days ago" sorts last
    return (job["first_seen"], posted, job["company"].lower())


def _table(jobs, today, show_new):
    lines = ["| Company | Role | Location | Posted | Apply |", "| --- | --- | --- | --- | :---: |"]
    cutoff = (today - timedelta(days=NEW_DAYS)).isoformat()
    for j in jobs:
        badge = "🆕 " if show_new and j["first_seen"] >= cutoff else ""
        loc = _cell(j["location"]) or "—"
        if len(loc) > 60:
            loc = loc[:57] + "…"
        lines.append(f"| **{_cell(j['company'])}** | {badge}{_cell(j['title'])} | {loc} | "
                     f"{j['posted'] or '—'} | [Apply]({j['url']}) |")
    return "\n".join(lines)


def write_markdown(path, jobs, errors, n_sources, show_new, us_only):
    today = date.today()
    interns = sorted([j for j in jobs if j["category"] == "Internship"], key=_sort_key, reverse=True)
    grads = sorted([j for j in jobs if j["category"] == "New Grad"], key=_sort_key, reverse=True)
    companies = len({j["company"] for j in jobs})

    out = [
        "# Semiconductor Internships & New-Grad Jobs",
        "",
        f"> **Last updated:** {today.isoformat()} · **{len(interns)}** internships · "
        f"**{len(grads)}** new-grad roles · **{companies}** companies · {n_sources} sources checked"
        + (" · US only" if us_only else ""),
        "",
        "Generated by [`scrape.py`](scrape.py). See the [README](README.md) for sources and how to run it."
        + (f" 🆕 = first seen in the last {NEW_DAYS} days." if show_new else ""),
        "",
        "**Jump to:** [Internships](#internships) · [New Grad](#new-grad) · [Source status](#source-status)",
        "",
        f"## Internships",
        "",
        _table(interns, today, show_new) if interns else "_None found this run._",
        "",
        f"## New Grad",
        "",
        _table(grads, today, show_new) if grads else "_None found this run._",
        "",
        "## Source status",
        "",
    ]
    if errors:
        out.append("These sources failed this run (their jobs are missing above):")
        out.append("")
        out += [f"- **{name}**: `{_cell(msg)[:150]}`" for name, msg in sorted(errors.items())]
    else:
        out.append("All sources fetched successfully.")
    out.append("")
    Path(path).write_text("\n".join(out), encoding="utf-8")


def write_data(data_dir, jobs):
    data_dir = Path(data_dir)
    data_dir.mkdir(exist_ok=True)
    fields = ["category", "company", "title", "location", "posted", "first_seen", "url", "source"]
    rows = sorted(jobs, key=lambda j: (j["category"], j["company"].lower(), j["title"].lower()))
    (data_dir / "jobs.json").write_text(json.dumps([{k: j[k] for k in fields} for j in rows], indent=1),
                                        encoding="utf-8")
    with open(data_dir / "jobs.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def load_seen(path):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def save_seen(path, seen):
    Path(path).write_text(json.dumps(seen, indent=0, sort_keys=True), encoding="utf-8")
